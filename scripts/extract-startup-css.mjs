// The legacy workspace sheet remains intact. Generate public-owned subsets in
// original cascade order; don't infer global dead code from one page's coverage.
// Uses the dashboard's existing PostCSS dependency (no package additions).
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
const require = createRequire(new URL("../dashboard/package.json", import.meta.url));
const postcss = require("postcss");
const source = new URL("../dashboard/src/app/globals.css", import.meta.url);
const common = new Set([
  "skip-link", "eyebrow", "button", "secondary", "ghost", "danger", "icon-button",
  "field", "field-label", "field-help", "input", "select", "textarea", "form-error",
  "status", "ready", "processing", "queued", "failed", "reviewed", "uploaded",
  "pill", "high", "medium", "low", "skeleton", "brand", "brand-mark", "brand-name",
  "brand-wordmark", "brand-lockup", "theme-toggle", "light", "dark",
  "panel", "loading-stack", "loading-row", "inline-state", "error-state", "quiet-panel", "content-heading",
  "google-mark", "signin-button",
]);
function project(node, mode) {
  if (node.type === "comment") return null;
  if (node.type === "rule") {
    const selectors = postcss.list.comma(node.selector).filter((selector) => {
      const classes = [...selector.matchAll(/\.([a-zA-Z_-][a-zA-Z0-9_-]*)/g)].map((m) => m[1]);
      if (mode === "base") return classes.every((name) => common.has(name));
      return classes.some((name) => /^(sample|auth|invite|shared)-/.test(name)) &&
        classes.every((name) => common.has(name) || /^(sample|auth|invite|shared)-/.test(name) || ["active", "good", "success", "warning", "info", "configured"].includes(name));
    });
    return selectors.length ? node.clone({ selector: selectors.join(", ") }) : null;
  }
  if (node.type === "atrule" && node.name === "import") return mode === "base" ? node.clone() : null;
  if (node.type === "atrule" && /keyframes$/.test(node.name)) return mode === "base" ? node.clone() : null;
  if (node.nodes) {
    const clone = node.clone(); clone.removeAll();
    for (const child of node.nodes) { const result = project(child, mode); if (result) clone.append(result); }
    return clone.nodes.length ? clone : null;
  }
  return null;
}
for (const mode of ["base", "public"]) {
  const root = postcss.root();
  for (const node of postcss.parse(readFileSync(source, "utf8")).nodes) {
    const result = project(node, mode); if (result) root.append(result);
  }
  const content = `/* Generated by scripts/extract-startup-css.mjs from globals.css. Preserve declarations/cascade; see docs/performance-startup-boundaries.md. */\n${root.toString()}\n`;
  const file = new URL(`../dashboard/src/app/${mode}.css`, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== content) throw new Error(`${mode}.css is out of date`);
  } else writeFileSync(file, content);
}
